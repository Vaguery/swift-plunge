import DequeModule

// shared protocol for the scalar Item types held inside a vector (Bool, Double,
// Int, String), so a vector Behavior can look up the stack its elements live on
// and construct new scalar Items generically
nonisolated protocol ScalarItem: Item {
    static var pushStack: PushStack { get }
    init(_ value: Value, call: [any Item], isContingent: Bool)
}

nonisolated extension BoolItem: ScalarItem {
    static var pushStack: PushStack { .bool }
}

nonisolated extension DoubleItem: ScalarItem {
    static var pushStack: PushStack { .double }
}

nonisolated extension IntItem: ScalarItem {
    static var pushStack: PushStack { .int }
}

nonisolated extension StringItem: ScalarItem {
    static var pushStack: PushStack { .string }
}


// shared protocol for the vector-valued Item types, so Behaviors that act
// the same way on every kind of vector can be generated by one function
nonisolated protocol VectorItem: Item where Value == [Element] {
    associatedtype Element
    associatedtype Scalar: ScalarItem where Scalar.Value == Element
    static var pushStack: PushStack { get }
    init(_ value: [Element], call: [any Item], isContingent: Bool)
}

nonisolated extension VecBoolItem: VectorItem {
    typealias Scalar = BoolItem
    static var pushStack: PushStack { .vecBool }
}

nonisolated extension VecDoubleItem: VectorItem {
    typealias Scalar = DoubleItem
    static var pushStack: PushStack { .vecDouble }
}

nonisolated extension VecIntItem: VectorItem {
    typealias Scalar = IntItem
    static var pushStack: PushStack { .vecInt }
}

nonisolated extension VecStringItem: VectorItem {
    typealias Scalar = StringItem
    static var pushStack: PushStack { .vecString }
}


nonisolated extension Interpreter {

    // returns a new vector (of the given type) with the old value's last element removed
    // if the argument was empty, an empty vector is pushed
    static func butLastBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            x.value.dropLast(1),
                            call: [x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x)
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector (of the given type) with the scalar argument appended
    static func conjBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                var result = x.value
                result.append(y.value)
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector formed by placing y's elements before x's
    static func concatBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, V.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            y.value + x.value,
                            call: [y, x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

