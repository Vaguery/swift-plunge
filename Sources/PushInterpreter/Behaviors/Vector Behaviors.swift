                    )
                ]
            }
        )
    }

    // returns a new vector with the first element removed
    static func restBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a, recording in
