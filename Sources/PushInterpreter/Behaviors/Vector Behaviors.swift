    }

    // returns the last y elements of the vector (y clamped to [0, count])
    static func takeBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                let idx = range - (min(range, max(y.value, 0)))
                let result = Array(x.value.dropLast(idx))

                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    // returns the vector with the first y elements removed (y clamped to [0, count])
    static func dropBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                let idx = (min(range, max(y.value, 0)))
                let result = Array(x.value.dropFirst(idx))

                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    // returns whether the vector contains the scalar argument (non-destructively:
    // both the vector and the needle survive the read)
    static func containsBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            reads: [V.pushStack, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.contains(y.value)
                return [
                    Router(
                        .bool,
                        BoolItem(
                            result,
                            call: Behavior.reading(
                                [V.pushStack: 1, V.Scalar.pushStack: 1],
                                producing: .bool,
                                from: [x, y, InstructionItem(instruction)]
                            ))
                    )
                ]
            }
        )
    }

    // returns the first element of the vector, or nothing if it is empty
    static func firstBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a, recording in
                let (x) = (a[0] as! V)
                if let result = x.value.first {
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, InstructionItem(instruction)])
                        )
                    ]
                } else {
                    return []
                }
            }
        )
    }

    // returns the last element of the vector, or nothing if it is empty
    static func lastBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a, recording in
                let (x) = (a[0] as! V)
                if let result = x.value.last {
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, InstructionItem(instruction)])
                        )
                    ]
                } else {
                    return []
                }
            }
        )
    }

    // returns the element at position y (wrapped modulo the vector's length),
    // or nothing if the vector is empty
    static func nthBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                if range == 0 {
                    return []
                } else {
                    // .magnitude (a UInt) avoids abs(Int.min) trapping;
                    // reducing modulo range keeps the wrapped-index semantics
                    let idx = Int(y.value.magnitude % UInt(range))
                    let result = x.value[idx]
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, y, InstructionItem(instruction)])
                        )
                    ]
                }
            }
        )
    }

    // returns the index of the first occurrence of the scalar argument, or -1
    // (non-destructively: both the vector and the needle survive the read)
    static func indexOfBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            reads: [V.pushStack, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.firstIndex(of: y.value) ?? -1
                return [
                    Router(
                        .int,
                        IntItem(
                            result,
                            call: Behavior.reading(
                                [V.pushStack: 1, V.Scalar.pushStack: 1],
                                producing: .int,
                                from: [x, y, InstructionItem(instruction)]
                            ))
                    )
                ]
            }
        )
    }

    // returns the number of occurrences of the scalar argument in the vector
    // (non-destructively: both the vector and the needle survive the read)
    static func occurrencesOfBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            reads: [V.pushStack, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.count(where: { $0 == y.value })
                return [
                    Router(
                        .int,
                        IntItem(
                            result,
                            call: Behavior.reading(
                                [V.pushStack: 1, V.Scalar.pushStack: 1],
                                producing: .int,
                                from: [x, y, InstructionItem(instruction)]
                            ))
                    )
                ]
            }
        )
    }

    /// A lexicographic ordering comparison of two vectors — the vector analog of
    /// `stringLT`/`stringGT`/etc. **Non-destructive**, like every comparison: it
    /// reads both operands and leaves them, and the crux pops the two it read
    /// (`Behavior.reading`). `V.Element: Comparable`, so `[9, 2] > [1, 1, 1]`
    /// (element-by-element, length only breaks ties) — Swift's built-in array
    /// order, not shortlex.
    ///
    /// `satisfied(y, x)` decides the result, given the two operands in record
    /// order (`y` deeper, `x` on top) — matching the scalar comparisons.
    static func comparisonBehavior<V: VectorItem>(
        _ instruction: PushInstruction,
        making itemType: V.Type,
        _ satisfied: @escaping @Sendable ([V.Element], [V.Element]) -> Bool
    ) -> Behavior where V.Element: Comparable {
        Behavior(
            instruction,
            reads: [V.pushStack, V.pushStack],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! V)
                return [
                    Router(
                        .bool,
                        BoolItem(
                            satisfied(y.value, x.value),
                            call: Behavior.reading(
                                [V.pushStack: 2],
                                producing: .bool,
                                from: [y, x, InstructionItem(instruction)]
                            ))
                    )
                ]
            }
        )
    }

    // MARK: - Sub-vector search and replace
    //
    // The whole-subsequence analogs of string's `stringContains`/`stringReplace`
    // (as opposed to the element-wise `contains`/`replace` above). All operands
    // are vectors on the same `V.pushStack`, so — unlike the element forms, whose
    // arguments split across the vector and scalar stacks — the crux records them
    // **reversed** (`[a[1], a[0], …]`), the same as `concatBehavior`, so re-running
    // rebuilds the same top-of-stack binding.

    /// The index at which `needle` first occurs contiguously in `hay`, or nil.
    /// An empty needle matches at 0 (a vacuous prefix), as `firstRange(of:)` does.
    static func firstSubIndex<E: Equatable>(_ hay: [E], _ needle: [E]) -> Int? {
        guard !needle.isEmpty else { return 0 }
        guard needle.count <= hay.count else { return nil }
        for start in 0...(hay.count - needle.count) {
            if hay[start..<start + needle.count].elementsEqual(needle) { return start }
        }
        return nil
    }

    /// Non-overlapping occurrences of `needle` in `hay`. An empty needle counts 0
    /// (it would otherwise match unboundedly).
    static func subCount<E: Equatable>(_ hay: [E], _ needle: [E]) -> Int {
        guard !needle.isEmpty, needle.count <= hay.count else { return 0 }
        var count = 0
        var i = 0
        while i <= hay.count - needle.count {
            if hay[i..<i + needle.count].elementsEqual(needle) { count += 1; i += needle.count }
            else { i += 1 }
        }
        return count
    }

    /// Whether the vector contains the **sub-vector** argument (contiguous),
    /// non-destructively — both vectors survive; the crux pops both.
    static func containsSubVecBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            reads: [V.pushStack, V.pushStack],
            fxn: { a, recording in
                let (hay, needle) = (a[0] as! V, a[1] as! V)
                return [
                    Router(
                        .bool,
                        BoolItem(
                            firstSubIndex(hay.value, needle.value) != nil,
                            call: Behavior.reading(
                                [V.pushStack: 2],
                                producing: .bool,
                                from: [needle, hay, InstructionItem(instruction)]
                            ))
                    )
                ]
            }
        )
    }

