    // returns the last y elements of the vector (y clamped to [0, count])
    static func takeBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                let idx = range - (min(range, max(y.value, 0)))
                let result = Array(x.value.dropLast(idx))

                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns the vector with the first y elements removed (y clamped to [0, count])
    static func dropBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                let idx = (min(range, max(y.value, 0)))
                let result = Array(x.value.dropFirst(idx))

                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns whether the vector contains the scalar argument
    static func containsBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.contains(y.value)
                return [
                    Router(
                        .bool,
                        BoolItem(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns the first element of the vector, or nothing if it is empty
    static func firstBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                if let result = x.value.first {
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x)
                            )
                        )
                    ]
                } else {
                    return []
                }
            }
        )
    }

    // returns the last element of the vector, or nothing if it is empty
    static func lastBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                if let result = x.value.last {
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x)
                            )
                        )
                    ]
                } else {
                    return []
                }
            }
        )
    }

    // returns the element at position y (wrapped modulo the vector's length),
    // or nothing if the vector is empty
    static func nthBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                if range == 0 {
                    return []
                } else {
                    // .magnitude (a UInt) avoids abs(Int.min) trapping;
                    // reducing modulo range keeps the wrapped-index semantics
                    let idx = Int(y.value.magnitude % UInt(range))
                    let result = x.value[idx]
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, y, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x, y)
                            )
                        )
                    ]
                }
            }
        )
    }

    // returns the index of the first occurrence of the scalar argument, or -1
    static func indexOfBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.firstIndex(of: y.value) ?? -1
                return [
                    Router(
                        .int,
                        IntItem(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns the number of occurrences of the scalar argument in the vector
    static func occurrencesOfBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.count(where: { $0 == y.value })
                return [
                    Router(
                        .int,
                        IntItem(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector with every occurrence of the scalar argument removed
    static func removeBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                var result = x.value
                result.removeAll(where: { $0 == y.value })
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // ( vec target replacement .vecXReplace )
    //
    // replace every occurrence of target in the vector with replacement
    //
    static func replaceBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! V.Scalar, a[2] as! V.Scalar)
                let result = x.value.map({ $0 == z.value ? y.value : $0 })
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z)
                        )
                    )
                ]
            }
        )
    }

    // ( vec target replacement .vecXReplaceFirst )
    //
    // replace the first occurrence of target in the vector with replacement
    //
    static func replaceFirstBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! V.Scalar, a[2] as! V.Scalar)
                var result = x.value
                if let idx = result.firstIndex(where: { $0 == z.value }) {
                    result[idx] = y.value
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z)
                        )
                    )
                ]
            }
        )
    }

    // ( vec position replacement .vecXSet )
    //
    // replace the element at position (wrapped modulo the vector's length) with replacement
    //
    static func setBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int, V.Scalar.pushStack],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! IntItem, a[2] as! V.Scalar)
                var result = x.value
                if result.count > 0 {
                    // .magnitude (a UInt) avoids abs(Int.min) trapping
                    let idx = Int(y.value.magnitude % UInt(result.count))
                    result[idx] = z.value
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z)
                        )
                    )
                ]
            }
        )
    }

    // ( vec idx1 idx2 .vecXSubVec )
    //
    // return a stretch of the original vector from positions idx1...idx2
    // if idx1 is negative, make it zero
    // if idx2 < idx1, return an empty vector
    //
    static func subVecBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int, .int],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! IntItem, a[2] as! IntItem)
                var result = x.value

                if result.count > 0 {
                    let range = result.count - 1
                    let lhs = min(range, max(0, z.value))
                    let rhs = min(range, max(0, z.value, y.value))
                    result = Array(result[lhs...rhs])
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z)
                        )
                    )
                ]
            }
        )
    }

    // ( vec .vecXPushAll )
    //
    // return every item on the argument (in reverse order)
    // routing them to the correct stack
    //
    static func pushAllBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                var results = [Router]()
                // Reversed before pushing, so element 0 ends up on TOP — the
                // opposite of `stringPushAllChars`, whose first char ends up
                // deepest. Law 5 counts from the end of the results either way.
                let backwards = Array(x.value.reversed())
                for idx in 0..<backwards.count {
                    results.append(
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                backwards[idx],
                                call: Behavior.selecting(
                                    idx,
                                    of: backwards.count,
                                    on: V.Scalar.pushStack,
                                    from: [x, InstructionItem(instruction)]
                                ),
                                isContingent: Behavior.netContingency(of: x)
                            )
                        )
                    )
                }
                return results
            }
        )
    }

    // ( vec .vecXIterate MOUSE )
    //
    //               4          3            2                   1         0
    // reults: ( exec:MOUSE exec:remains exec:.vecXIterate exec:MOUSE scalar:CHEESE )
    //
    static func iterateBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        // The two derived values here are the element pulled off the front and
        // the vector left behind, and each is honestly described by an existing
        // instruction — `.vecXFirst` and `.vecXRest` — rather than by the
        // iterate instruction that happened to produce them. Naming the iterate
        // instruction was both unrunnable (its crux re-ran the whole loop, mouse
        // and all) and unbounded. Naming `First`/`Rest` also makes the mouse
        // genuinely irrelevant to the element's provenance, which is why it no
        // longer appears in the `call`.
        let firstInstruction =
            PushInstruction(rawValue: "\(V.pushStack.rawValue)First")!
        let restInstruction =
            PushInstruction(rawValue: "\(V.pushStack.rawValue)Rest")!

        return Behavior(
            instruction,
            takes: [V.pushStack, .exec],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1])
                var results = [Router]()
                var workingVector = x.value

                let count = workingVector.count
                if count > 0 {
                    // The mouse and the re-pushed iterate token are combinatory
                    // (laws 1 and 4) and record nothing.
                    results.append(Router(.exec, y))

                    let item = workingVector.removeFirst()
                    results.append(
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                item,
                                call: [x, InstructionItem(firstInstruction)],
                                isContingent: Behavior.netContingency(of: x, y)
                            )
                        )
                    )
                    if count > 1 {
                        results.append(
                            Router(
                                .exec,
                                InstructionItem(
                                    instruction,
                                    isContingent: Behavior.netContingency(
                                        of: x,
                                        y
                                    )
                                )
                            )
                        )
                        results.append(
                            Router(
                                .exec,
                                V(
                                    workingVector,  // which was changed
                                    call: [x, InstructionItem(restInstruction)],
                                    isContingent: Behavior.netContingency(
                                        of: x,
                                        y
                                    )
                                )
                            )
                        )
                        results.append(Router(.exec, y))
                    }
                }
                return results
            }
        )
    }

