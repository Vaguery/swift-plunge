import DequeModule

// shared protocol for the scalar Item types held inside a vector (Bool, Double,
// Int, String), so a vector Behavior can look up the stack its elements live on
// and construct new scalar Items generically
protocol ScalarItem: Item {
    static var pushStack: PushStack { get }
    init(_ value: Value, call: [any Item], isContingent: Bool, index: Int)
}

extension BoolItem: ScalarItem {
    static var pushStack: PushStack { .bool }
}

extension DoubleItem: ScalarItem {
    static var pushStack: PushStack { .double }
}

extension IntItem: ScalarItem {
    static var pushStack: PushStack { .int }
}

extension StringItem: ScalarItem {
    static var pushStack: PushStack { .string }
}


// shared protocol for the vector-valued Item types, so Behaviors that act
// the same way on every kind of vector can be generated by one function
protocol VectorItem: Item where Value == [Element] {
    associatedtype Element
    associatedtype Scalar: ScalarItem where Scalar.Value == Element
    static var pushStack: PushStack { get }
    init(_ value: [Element], call: [any Item], isContingent: Bool, index: Int)
}

extension VecBoolItem: VectorItem {
    typealias Scalar = BoolItem
    static var pushStack: PushStack { .vecBool }
}

extension VecDoubleItem: VectorItem {
    typealias Scalar = DoubleItem
    static var pushStack: PushStack { .vecDouble }
}

extension VecIntItem: VectorItem {
    typealias Scalar = IntItem
    static var pushStack: PushStack { .vecInt }
}

extension VecStringItem: VectorItem {
    typealias Scalar = StringItem
    static var pushStack: PushStack { .vecString }
}


extension Interpreter {

    // returns a new vector (of the given type) with the old value's last element removed
    // if the argument was empty, an empty vector is pushed
    static func butLastBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            x.value.dropLast(1),
                            call: [x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector (of the given type) with the scalar argument appended
    static func conjBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                var result = x.value
                result.append(y.value)
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector formed by placing y's elements before x's
    static func concatBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, V.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            y.value + x.value,
                            call: [y, x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns whether the vector argument is empty
    static func itemIsEmptyBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                return [
                    Router(
                        .bool,
                        BoolItem(
                            x.value.isEmpty,
                            call: [x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x)
                        )
                    )
                ]
            }
        )
    }

    // returns the number of elements in the vector argument
    static func lengthBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                return [
                    Router(
                        .int,
                        IntItem(
                            x.value.count,
                            call: [x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x)
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector with the first element removed
    static func restBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            Array(x.value.dropFirst(1)),
                            call: [x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector with the elements in reverse order
    static func reverseBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            Array(x.value.reversed()),
                            call: [x, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns the last y elements of the vector (y clamped to [0, count])
    static func takeBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                let idx = range - (min(range, max(y.value, 0)))
                let result = Array(x.value.dropLast(idx))

                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns the vector with the first y elements removed (y clamped to [0, count])
    static func dropBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                let idx = (min(range, max(y.value, 0)))
                let result = Array(x.value.dropFirst(idx))

                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // returns whether the vector contains the scalar argument
    static func containsBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.contains(y.value)
                return [
                    Router(
                        .bool,
                        BoolItem(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns the first element of the vector, or nothing if it is empty
    static func firstBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                if let result = x.value.first {
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x),
                                index: 0
                            )
                        )
                    ]
                } else {
                    return []
                }
            }
        )
    }

    // returns the last element of the vector, or nothing if it is empty
    static func lastBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                if let result = x.value.last {
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x),
                                index: 0
                            )
                        )
                    ]
                } else {
                    return []
                }
            }
        )
    }

    // returns the element at position y (wrapped modulo the vector's length),
    // or nothing if the vector is empty
    static func nthBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let range = x.value.count
                if range == 0 {
                    return []
                } else {
                    let position = abs(y.value)
                    let idx = position % range
                    let result = x.value[idx]
                    return [
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                result,
                                call: [x, y, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x, y),
                                index: 0
                            )
                        )
                    ]
                }
            }
        )
    }

    // returns the index of the first occurrence of the scalar argument, or -1
    static func indexOfBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.firstIndex(of: y.value) ?? -1
                return [
                    Router(
                        .int,
                        IntItem(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns the number of occurrences of the scalar argument in the vector
    static func occurrencesOfBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                let result = x.value.count(where: { $0 == y.value })
                return [
                    Router(
                        .int,
                        IntItem(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y)
                        )
                    )
                ]
            }
        )
    }

    // returns a new vector with every occurrence of the scalar argument removed
    static func removeBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                var result = x.value
                result.removeAll(where: { $0 == y.value })
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // ( vec target replacement .vecXReplace )
    //
    // replace every occurrence of target in the vector with replacement
    //
    static func replaceBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! V.Scalar, a[2] as! V.Scalar)
                let result = x.value.map({ $0 == z.value ? y.value : $0 })
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // ( vec target replacement .vecXReplaceFirst )
    //
    // replace the first occurrence of target in the vector with replacement
    //
    static func replaceFirstBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack, V.Scalar.pushStack],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! V.Scalar, a[2] as! V.Scalar)
                var result = x.value
                if let idx = result.firstIndex(where: { $0 == z.value }) {
                    result[idx] = y.value
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // ( vec position replacement .vecXSet )
    //
    // replace the element at position (wrapped modulo the vector's length) with replacement
    //
    static func setBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int, V.Scalar.pushStack],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! IntItem, a[2] as! V.Scalar)
                var result = x.value
                if result.count > 0 {
                    let idx = abs(y.value) % (result.count)
                    result[idx] = z.value
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // ( vec idx1 idx2 .vecXSubVec )
    //
    // return a stretch of the original vector from positions idx1...idx2
    // if idx1 is negative, make it zero
    // if idx2 < idx1, return an empty vector
    //
    static func subVecBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int, .int],
            fxn: { a in
                let (x, y, z) = (a[0] as! V, a[1] as! IntItem, a[2] as! IntItem)
                var result = x.value

                if result.count > 0 {
                    let range = result.count - 1
                    let lhs = min(range, max(0, z.value))
                    let rhs = min(range, max(0, z.value, y.value))
                    result = Array(result[lhs...rhs])
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)],
                            isContingent: Behavior.netContingency(of: x, y, z),
                            index: 0
                        )
                    )
                ]
            }
        )
    }

    // ( vec .vecXPushAll )
    //
    // return every item on the argument (in reverse order)
    // routing them to the correct stack
    //
    static func pushAllBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a in
                let (x) = (a[0] as! V)
                var results = [Router]()
                let backwards = Array(x.value.reversed())
                for idx in 0..<backwards.count {
                    results.append(
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                backwards[idx],
                                call: [x, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x),
                                index: backwards.count - idx - 1
                            )
                        )
                    )
                }
                return results
            }
        )
    }

    // ( vec .vecXIterate MOUSE )
    //
    //               4          3            2                   1         0
    // reults: ( exec:MOUSE exec:remains exec:.vecXIterate exec:MOUSE scalar:CHEESE )
    //
    static func iterateBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .exec],
            fxn: { a in
                let (x, y) = (a[0] as! V, a[1])
                var results = [Router]()
                var workingVector = x.value

                var mouseCopy = a[1]
                let count = workingVector.count
                if count > 0 {
                    mouseCopy.index = 1
                    results.append(Router(.exec, mouseCopy))  //1

                    let item = workingVector.removeFirst()
                    results.append(
                        Router(
                            V.Scalar.pushStack,
                            V.Scalar(
                                item,
                                call: [x, InstructionItem(instruction)],
                                isContingent: Behavior.netContingency(of: x, y),
                                index: 0
                            )
                        )
                    )
                    if count > 1 {
                        results.append(
                            Router(
                                .exec,
                                InstructionItem(
                                    instruction,
                                    call: [x, InstructionItem(instruction)],
                                    isContingent: Behavior.netContingency(
                                        of: x,
                                        y
                                    ),
                                    index: 2
                                )
                            )
                        )
                        results.append(
                            Router(
                                .exec,
                                V(
                                    workingVector,  // which was changed
                                    call: [x, InstructionItem(instruction)],
                                    isContingent: Behavior.netContingency(
                                        of: x,
                                        y
                                    ),
                                    index: 3
                                )
                            )
                        )
                        mouseCopy.index = 4
                        results.append(Router(.exec, mouseCopy))  //4
                    }
                }
                return results
            }
        )
    }
}
