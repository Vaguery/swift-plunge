            }
        )
    }

    // returns a new vector with the elements in reverse order
    static func reverseBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a, recording in
                let (x) = (a[0] as! V)
                return [
