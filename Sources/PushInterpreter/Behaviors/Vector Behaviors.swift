    /// Replace **every** non-overlapping occurrence of a sub-vector with another
    /// sub-vector — a transform, so it **consumes** all three arguments. The
    /// subject is the deepest, then the needle, then the replacement on top; the
    /// crux re-pushes them in that order.
    static func replaceSubVecBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.pushStack, V.pushStack],
            fxn: { a, recording in
                let (repl, needle, subject) = (a[0] as! V, a[1] as! V, a[2] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            replacingSub(subject.value, needle.value, repl.value, firstOnly: false),
                            call: [subject, needle, repl, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    /// Replace only the **first** occurrence of a sub-vector. Consumes, like its
    /// replace-all sibling.
    static func replaceFirstSubVecBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.pushStack, V.pushStack],
            fxn: { a, recording in
                let (repl, needle, subject) = (a[0] as! V, a[1] as! V, a[2] as! V)
                return [
                    Router(
                        V.pushStack,
                        V(
                            replacingSub(subject.value, needle.value, repl.value, firstOnly: true),
                            call: [subject, needle, repl, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    /// Substitute `repl` for occurrences of `needle` in `hay`, left to right,
    /// non-overlapping. An empty needle matches nothing (returns `hay` unchanged),
    /// which is the only sane reading — otherwise it would splice `repl` between
    /// every element.
    static func replacingSub<E: Equatable>(_ hay: [E], _ needle: [E], _ repl: [E], firstOnly: Bool) -> [E] {
        guard !needle.isEmpty, needle.count <= hay.count else { return hay }
        var result: [E] = []
        var i = 0
        var replaced = false
        while i < hay.count {
            if (!firstOnly || !replaced),
               i <= hay.count - needle.count,
               hay[i..<i + needle.count].elementsEqual(needle) {
                result.append(contentsOf: repl)
                i += needle.count
                replaced = true
            } else {
                result.append(hay[i])
                i += 1
            }
        }
        return result
    }

    // returns a new vector with every occurrence of the scalar argument removed
    static func removeBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! V.Scalar)
                var result = x.value
                result.removeAll(where: { $0 == y.value })
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    // ( vec target replacement .vecXReplace )
    //
    // replace every occurrence of target in the vector with replacement
    //
    static func replaceBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y, z) = (a[0] as! V, a[1] as! V.Scalar, a[2] as! V.Scalar)
                let result = x.value.map({ $0 == z.value ? y.value : $0 })
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    // ( vec target replacement .vecXReplaceFirst )
    //
    // replace the first occurrence of target in the vector with replacement
    //
    static func replaceFirstBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior where V.Element: Equatable {
        Behavior(
            instruction,
            takes: [V.pushStack, V.Scalar.pushStack, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y, z) = (a[0] as! V, a[1] as! V.Scalar, a[2] as! V.Scalar)
                var result = x.value
                if let idx = result.firstIndex(where: { $0 == z.value }) {
                    result[idx] = y.value
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    // ( vec position replacement .vecXSet )
    //
    // replace the element at position (wrapped modulo the vector's length) with replacement
    //
    static func setBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int, V.Scalar.pushStack],
            fxn: { a, recording in
                let (x, y, z) = (a[0] as! V, a[1] as! IntItem, a[2] as! V.Scalar)
                var result = x.value
                if result.count > 0 {
                    // .magnitude (a UInt) avoids abs(Int.min) trapping
                    let idx = Int(y.value.magnitude % UInt(result.count))
                    result[idx] = z.value
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    // ( vec idx1 idx2 .vecXSubVec )
    //
    // return a stretch of the original vector from positions idx1...idx2
    // if idx1 is negative, make it zero
    // if idx2 < idx1, return an empty vector
    //
    static func subVecBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int, .int],
            fxn: { a, recording in
                let (x, y, z) = (a[0] as! V, a[1] as! IntItem, a[2] as! IntItem)
                var result = x.value

                if result.count > 0 {
                    let range = result.count - 1
                    let lhs = min(range, max(0, z.value))
                    let rhs = min(range, max(0, z.value, y.value))
                    result = Array(result[lhs...rhs])
                }
                return [
                    Router(
                        V.pushStack,
                        V(
                            result,
                            call: [x, z, y, InstructionItem(instruction)])
                    )
                ]
            }
        )
    }

    /// Snips a vector into two pieces at the indexed position, pushing **both** to
    /// the same stack: the prefix `[0..<idx]` deeper, the suffix `[idx..<count]`
    /// on top.
    ///
    /// **The order is chosen so `cut` then `concat` is the identity.** `concat`
    /// consumes the deeper argument first (`a[1].value + a[0].value`), so with the
    /// prefix underneath, `prefix + suffix` rebuilds the original vector.
    ///
    /// **The index wraps** — `magnitude % count` maps any int into `[0, count)`,
    /// avoiding the `Int.min` trap and matching the `nth` family's wrapped-index
    /// reading. Two consequences of the wrap, both deliberate: an index of exactly
    /// `count` wraps to 0, so the suffix is **never empty** for a non-empty
    /// argument (you cannot cut off the whole thing and leave nothing); and the
    /// prefix is empty exactly when the cut lands at 0. Cutting an empty vector
    /// gives two empty vectors.
    ///
    /// **Provenance is law 5** (`Behavior.selecting`, Items.swift): two results on
    /// one stack. The deeper piece records the discard that surfaces it —
    /// `x y .vecXCut 1 .vecXPopItems` — and the top piece records just the cut.
    /// This is the machinery the explode family retired; a cut is the honest
    /// multi-result case it was built for, so it has a user again.
    static func cutBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .int],
            fxn: { a, recording in
                let (x, y) = (a[0] as! V, a[1] as! IntItem)
                let count = x.value.count
                // `.magnitude` (a UInt) avoids `abs(Int.min)` trapping; the modulo
                // is skipped on an empty vector, where it would divide by zero.
                let idx = count == 0 ? 0 : Int(y.value.magnitude % UInt(count))

                let prefix = Array(x.value[0..<idx])
                let suffix = Array(x.value[idx...])
                let source: [any Item] = [x, y, InstructionItem(instruction)]

                return [
                    Router(V.pushStack, V(
                        prefix,
                        call: Behavior.selecting(0, of: 2, on: V.pushStack, from: source))),
                    Router(V.pushStack, V(
                        suffix,
                        call: Behavior.selecting(1, of: 2, on: V.pushStack, from: source))),
                ]
            }
        )
    }

    // ( vec .vecXPushAll )
    /// Pushes every element of a vector to its scalar stack, **one per pass**,
    /// front to back — so the last element ends up on top.
    ///
    /// **The order changed here, deliberately.** This used to reverse before
    /// pushing, so element 0 landed on top, while its sibling
    /// `stringPushAllChars` left the *last* character on top. Two instructions
    /// doing the same job and disagreeing about a basic question, for years —
    /// each internally consistent, neither wrong on its own. Walking front to back
    /// settles it; see "Collections are walked front-to-back" in
    /// "Notes on Push/Design Principles.md".
    ///
    /// It also used to explode in a single step, which put the work beyond
    /// `stepLimit` and the runaway guard, and forced every element to record which
    /// of the pile it was (a law-5 selection). Each element now records
    /// `v 2 .vecIntNth`: independent, O(1), and true however many passes have run.
    ///
    /// A sequence, not a loop: no body, so a pass costs one step rather than three.
    /// Builds a vector out of scalars, using an existing vector **as a shape**:
    /// it takes as many items off the scalar stack as the template has elements,
    /// and never looks at the template's contents at all.
    ///
    /// This is the exact **inverse of `pushAll`**, and that is where its argument
    /// order comes from. `[1, 22, 333] .vecIntPushAll` leaves `.int` reading
    /// `[ 333 22 1 ]` top-to-bottom, so Construct pops top-first and the **first
    /// item popped becomes the LAST element** — round-tripping the pair back to the
    /// vector you started with. The postfix reading agrees, which is the useful
    /// check: `1 22 333 ( a 3-element vector ) .vecIntConstruct` yields
    /// `[1, 22, 333]`, in the order you wrote them (Design Principles §2, §6).
    ///
    /// **It does not open the closed system.** A program still cannot make a vector
    /// out of nothing — it needs one to shape the new one, so the vector stacks
    /// remain seeded-only (see "Stack economics.md" §2). What it *does* buy is the
    /// thing that was actually missing: until now a vector's contents could only be
    /// rearranged, never **computed**. Every element of the result can be something
    /// the program worked out.
    ///
    /// Too few scalars and nothing happens — and it no longer has to arrange that
    /// itself. **This is the instruction the planner was built for**: "N items from
    /// the scalar stack, where N is the length of my other argument" is a
    /// requirement no static declaration can express, and for a while it was the
    /// only thing in the language keeping the all-or-nothing bargain by hand.
    /// `.takesMany` says it outright, so the Planner refuses before anything is
    /// taken, and the refusal reads like every other missing argument.
    ///
    /// Provenance: a genuinely new value, recording law 3 — the template first (as
    /// `conj` and the rest of the vector family order it), then the elements in
    /// source order, then the instruction. The record is O(N) in the vector's
    /// length, which is honest: an N-element vector really does have N elements'
    /// worth of history, and `maxCallWeight` bounds it like any other honest growth.
    static func constructBehavior<V: VectorItem>(
        _ instruction: PushInstruction,
        making itemType: V.Type
    ) -> Behavior {
        Behavior(
            instruction,
            requires: [
                .takes(V.pushStack),
                // N scalars, where N is the shape's length — the requirement that
                // could not be declared before there was a planner to declare it to.
                .takesMany(V.Scalar.pushStack, count: { args in
                    (args[0] as? V)?.value.count ?? 0
                }),
            ],
            fxn: { a, recording in
                let template = a[0] as! V
                // Top-first out of the planner, so reversing puts the first-written
                // element first — the same order `pushAll` would put them back in.
                let elements: [V.Scalar] = a.dropFirst().map { $0 as! V.Scalar }.reversed()

                let record: [any Item] =
                    [template] + elements.map { $0 as any Item } + [InstructionItem(instruction)]

                return [
                    Router(
                        V.pushStack,
                        V(
                            elements.map(\.value),
                            call: record)
                    )
                ]
            }
        )
    }

    // MARK: - Read-only constructors (the stack "backup" / snapshot)
    //
    // Build a vector from the scalars on its `X` stack **without consuming them** —
    // the closed-system fix (a program can finally create a vector) and a
    // non-destructive snapshot of the stack. They reach into the stack directly
    // (a `BehaviorWithSideEffects`, because the count is dynamic), and leave the
    // scalars in place.
    //
    // The crux always reconstructs via the fixed-count `readItems` form (never
    // `readStack`, which reads the whole stack and so could pick up an earlier
    // fragment's debris when composed): it re-pushes exactly the k scalars it
    // read, rebuilds the same vector, and pops those k. Debris-free and composable.

    /// The `call` a read-only constructor records: push the `k` scalars (keeping
    /// their own provenance), rebuild the vector with `readItems k`, then pop the
    /// k scalars. `readInstruction` is the type's fixed-count `…ReadItems`.
    static func snapshotCrux<V: VectorItem>(
        _ scalars: [V.Scalar],
        readInstruction: PushInstruction,
        making itemType: V.Type
    ) -> [any Item] {
        // `scalars` are in vector order (element 0 first). Re-pushed in that order,
        // element 0 ends up deepest; `readItems` reads top-first and reverses, so
        // element 0 comes back to the front — the round trip is exact.
        Behavior.reading(
            [V.Scalar.pushStack: scalars.count],
            producing: V.pushStack,
            from: scalars.map { $0 as any Item }
                + [IntItem(scalars.count), InstructionItem(readInstruction)]
        )
    }

    /// Read the top `N` scalars of the `X` stack into a new vector, leaving them in
    /// place. `N` is clamped to `[0, available]`.
    static func readItemsBehavior<V: VectorItem>(
        _ instruction: PushInstruction, making itemType: V.Type
    ) -> Behavior {
        BehaviorWithSideEffects(
            instruction,
            takes: [.int],
            modifier: { (interpreter, collected) in
                let n = (collected[0] as! IntItem).value
                let stack = V.Scalar.pushStack
                let available = interpreter.stacks[stack]!.count
                let k = min(max(0, n), available)
                // Top k, top-first, reversed so the first-read scalar is the last
                // element — the inverse of `pushAll`, matching `vecXConstruct`.
                let elements = Array(interpreter.stacks[stack]!.prefix(k))
                    .map { $0 as! V.Scalar }
                    .reversed()
                    .map { $0 }
                return [
                    Router(
                        V.pushStack,
                        V(
                            elements.map(\.value),
                            call: snapshotCrux(elements, readInstruction: instruction, making: V.self))
                    )
                ]
            }
        )
    }

    /// Read the **whole** `X` stack into a new vector, leaving it in place. An
    /// empty stack gives an empty vector. The result depends on the entire
    /// stack's arrangement (like `StackDepth`), and its crux reconstructs via
    /// `readItems`, so it stays composable.
    static func readStackBehavior<V: VectorItem>(
        _ instruction: PushInstruction,
        readItemsInstruction: PushInstruction,
        making itemType: V.Type
    ) -> Behavior {
        BehaviorWithSideEffects(
            instruction,
            takes: [],
            modifier: { (interpreter, _) in
                let stack = V.Scalar.pushStack
                let elements = Array(interpreter.stacks[stack]!)
                    .map { $0 as! V.Scalar }
                    .reversed()
                    .map { $0 }
                return [
                    Router(
                        V.pushStack,
                        V(
                            elements.map(\.value),
                            call: snapshotCrux(elements, readInstruction: readItemsInstruction, making: V.self))
                    )
                ]
            }
        )
    }

    static func pushAllBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack],
            fxn: { a, recording in
                let x = a[0] as! V
                guard !x.value.isEmpty else { return [] }
                return Interpreter.iteratorLoop(
                    kind: .elements(into: nil),
                    origin: x,
                    body: nil,
                    emits: true, recording: recording
                )
            }
        )
    }

    /// Runs the mouse once per element of the vector, leaving each element on the
    /// matching scalar stack for it to read.
    ///
    /// Like `stringIterate`, this used to carry its own state in Push: every pass
    /// re-pushed the *remaining* vector and a fresh token, so the shrinking
    /// remainder recorded `[previous, .vecXRest]` — one level deeper per element,
    /// O(n), and bounded only by the `maxCallWeight` backstop, which meant a long
    /// vector lost its story. The iterator keeps the whole vector and a cursor, so
    /// each element records `v 2 .vecXNth`: O(1), and independent of how many
    /// passes have run.
    ///
    /// `.vecXFirst`/`.vecXRest` are no longer named by anything here. They were the
    /// honest description of a *shrinking* walk; there is no shrinking now.
    static func iterateBehavior<V: VectorItem>(_ instruction: PushInstruction, making itemType: V.Type) -> Behavior {
        Behavior(
            instruction,
            takes: [V.pushStack, .code],
            // All four `vecXIterate` at once — the factory is the right place for a
            // family judgment, because there is then no way to tag three of four.
            tags: [.reEntrant],
            fxn: { a, recording in
                let (x, mouse) = (a[0] as! V, a[1] as! CodeItem)
                guard !x.value.isEmpty else { return [] }
                return Interpreter.iteratorLoop(
                    kind: .elements(into: nil),
                    origin: x,
                    body: mouse,
                    emits: true, recording: recording
                )
            }
        )
    }

